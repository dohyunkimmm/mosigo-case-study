import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base=process.env.SITE_QA_URL||'http://127.0.0.1:8765/';
const prefix=process.env.SITE_QA_MODE==='live'?'live-':'';
await mkdir('qa-artifacts',{recursive:true});
const browser=await chromium.launch({headless:true});
try{
 for(const width of [390,1440]){
  const page=await browser.newPage({viewport:{width,height:900},reducedMotion:'reduce'});
  const failures=[];
  page.on('pageerror',error=>failures.push(error.message));
  const response=await page.goto(base,{waitUntil:'domcontentloaded',timeout:45000});
  assert.equal(response.status(),200);
  assert.equal(await page.locator('.v3-phase-link').count(),0,'duplicate phase shortcuts removed');
  assert.equal(await page.locator('.nav-link').count(),9,'primary contents navigation retained');
  assert.equal(await page.locator('.hero-actions a[href="#decision"]').count(),0,'decision shortcut is provided in the contents');
  assert.equal(await page.locator('.hero-actions a[href="#attachments"]').count(),1,'business plan is a visible hero CTA');
  assert.equal(await page.locator('.hero-actions a[href="downloads/mosigo_prd_delivery.html"]').count(),0,'PRD is not the primary hero action');
  assert.equal(await page.locator('.business-model-choice article.is-priority').count(),1,'one conditional priority business model');
  assert.equal(await page.locator('.decision-gates li').count(),3,'final decision has three conditional approval gates');
  assert.equal(await page.locator('.v3-hero-metric').count(),3,'hero metrics');
  assert.equal(await page.locator('.v3-product-card').count(),3,'three verified concept wireframes');
  assert.match(await page.locator('.v3-product-intro').textContent(),/개념\s*시안\s*3종/,'three concept screens are clearly labeled');
  assert.equal(await page.locator('.v3-scenario-picks button').count(),3);
  assert.equal(await page.locator('.v3-bar-col').count(),4,'three presets plus current assumptions');
  assert.equal(await page.locator('#v3-doc-thumbs,#v3-doc-page,#v3-view-full').count(),0);
  assert.equal(await page.locator('#doc-pptx-save').isHidden(),true,'plan has a PDF only');
  const start=await page.evaluate(()=>({x:document.documentElement.scrollWidth,w:document.documentElement.clientWidth}));
  assert.ok(start.x<=start.w+1,width+'px document fits viewport');
  await page.locator('#business .chapter-detail summary').click();
  await page.locator('[data-v3-scenario="conservative"]').click();
  assert.equal(await page.locator('#users').inputValue(),'8000');
  assert.equal(await page.locator('#freq').inputValue(),'1');
  assert.equal((await page.locator('#margin').textContent()).trim(),'4000.00만 원');
  assert.ok(new URL(page.url()).searchParams.get('v_users')==='8000');
  await page.locator('[data-v3-scenario="growth"]').click();
  assert.equal(await page.locator('#users').inputValue(),'20000');
  assert.equal(await page.locator('#price').inputValue(),'45000');
  assert.equal((await page.locator('#margin').textContent()).trim(),'6.00억 원');
  assert.equal(await page.locator('[data-v3-scenario="growth"]').getAttribute('aria-pressed'),'true');
  await page.reload({waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('#users').inputValue(),'20000','shared URL restores slider state');
  await page.locator('#business .chapter-detail summary').click();
  await page.locator('#reset').click();
  assert.equal(await page.locator('#users').inputValue(),'15000');
  assert.equal(new URL(page.url()).searchParams.has('v_users'),false,'reset removes nondefault query');
  await page.locator('#doc-next').click();
  await page.locator('#doc-next').click();
  assert.ok((await page.locator('#doc-page-img').getAttribute('src')).endsWith('plan-03-sm.webp'));
  await page.locator('[data-doc-preview="presentation"]').click();
  assert.match(await page.locator('#doc-pptx-save').getAttribute('href'),/mosigo_report\.pptx$/);

  assert.ok((await page.locator('#doc-page-img').getAttribute('src')).endsWith('slides-01-sm.webp'));
  await page.locator('#doc-page-open').click();
  assert.equal(await page.locator('#v3-fullscreen').evaluate(x=>x.open),true,'full-screen dialog opens');
  await page.locator('#v3-doc-zoom').click();
  assert.equal(await page.locator('#v3-doc-zoom').getAttribute('aria-pressed'),'true','expanded preview supports zoom');
  assert.equal(await page.locator('.v3-zoom-viewport').evaluate(e=>e.scrollWidth>e.clientWidth),true,'zoom supports horizontal reading');
  await page.locator('#v3-full-close').click();
  assert.equal(await page.locator('#v3-fullscreen').evaluate(x=>x.open),false,'dialog closes');
  await page.locator('[data-doc-preview="ir"]').click();
  assert.match(await page.locator('#doc-pptx-save').getAttribute('href'),/MOSIGO_IR_Investment_Review_12slides\.pptx$/);
  await page.waitForFunction(() => document.querySelector('#doc-page-img')?.getAttribute('src')?.endsWith('ir-01-sm.webp'));
  await page.locator('#doc-next').click();
  await page.locator('#doc-next').click();
  assert.ok((await page.locator('#doc-page-img').getAttribute('src')).endsWith('ir-03-sm.webp'),'IR next control changes page');
  await page.locator('#doc-page-open').click();
  assert.ok((await page.locator('#v3-fullscreen-img').getAttribute('src')).endsWith('ir-03.webp'),'IR fullscreen matches selected page');
  assert.equal(await page.locator('#v3-fullscreen').evaluate(x=>x.open),true,'IR fullscreen opens');
  await page.locator('#v3-full-close').click();
  await page.locator('[data-doc-preview="plan"]').click();
  assert.equal(await page.locator('#v3-page-share').count(),0,'extra page-share button removed');
  const end=await page.evaluate(()=>({x:document.documentElement.scrollWidth,w:document.documentElement.clientWidth}));
  assert.ok(end.x<=end.w+1,width+'px no horizontal overflow after interactions');
  assert.ok((await page.locator('#doc-page-img').getAttribute('src')).endsWith('plan-03-sm.webp'),'plan page remembered when switching documents');
  await page.locator('#doc-prev').click();
  assert.ok((await page.locator('#doc-page-img').getAttribute('src')).endsWith('plan-02-sm.webp'),'previous-page control works');
  await page.locator('#doc-page-open').click();
  assert.equal(await page.locator('#v3-fullscreen').evaluate(x=>x.open),true,'page preview opens in a dialog');
  await page.locator('#v3-full-next').click();
  assert.ok((await page.locator('#v3-fullscreen-img').getAttribute('src')).endsWith('plan-03.webp'),'dialog next-page control advances the preview');
  await page.locator('#v3-full-close').click();
  assert.equal(await page.locator('#v3-fullscreen').evaluate(x=>x.open),false,'dialog closes after navigation');
  assert.equal(await page.locator('.review-verification article').count(),4);
  const printStates = await page.evaluate(() => {
    const chapters = [...document.querySelectorAll('.chapter-detail')];
    chapters[0].open = true;
    chapters[1].open = false;
    const before = chapters.map(chapter => chapter.open);
    window.dispatchEvent(new Event('beforeprint'));
    const expanded = chapters.every(chapter => chapter.open);
    window.dispatchEvent(new Event('afterprint'));
    return {before,expanded,after:chapters.map(chapter => chapter.open)};
  });
  assert.ok(printStates.expanded,'all chapters appear in print');
  assert.deepEqual(printStates.after,printStates.before,'chapter state restored after print');
  const partner = page.locator('#partner-results');
  assert.match(await partner.textContent(),/199건.*3,700원.*541건.*1,082건/,'partner scenario matches baseline');
  assert.deepEqual(failures,[],width+'px no page JS errors');
  await page.screenshot({path:'qa-artifacts/'+prefix+'v3-'+width+'.png',fullPage:true});
  console.log('PASS v3 progressive interactions',width,{start,end});
  await page.close();
 }
 const bad=await browser.newPage({viewport:{width:390,height:800}});
 await bad.goto(new URL('?v_users=-1&v_price=NaN&v_freq=88',base).href,{waitUntil:'load'});
 assert.equal(await bad.locator('#users').inputValue(),'15000','invalid shared values ignored');
 assert.equal(await bad.locator('#price').inputValue(),'40000');
 await bad.close();
 console.log('PASS v3 share safety and controls');
}finally{await browser.close();}
